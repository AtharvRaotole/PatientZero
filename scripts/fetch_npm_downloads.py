"""Fetch npm downloads for the 19 qix-compromised packages for the week before the attack (2025-09-01..07).

Writes data/raw/npm-downloads/qix-week-before.json and frontend/src/lib/facts.ts (the hero figure).
Source: https://api.npmjs.org/downloads/point/<period>/<pkg>. Run: python3 scripts/fetch_npm_downloads.py
"""
import json
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PERIOD = "2025-09-01:2025-09-07"
inc = json.loads((ROOT / "data/incidents/2025-09-08-qix.json").read_text())
pkgs = sorted({c.get("package") or c["pkg"] for c in inc["compromised"]})
out = {"source": f"https://api.npmjs.org/downloads/point/{PERIOD}/<pkg>", "period": PERIOD,
       "fetched_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()), "packages": {}}
for p in pkgs:
    req = urllib.request.Request(f"https://api.npmjs.org/downloads/point/{PERIOD}/{p}", headers={"User-Agent": "patientzero"})
    out["packages"][p] = json.load(urllib.request.urlopen(req, timeout=20))["downloads"]
out["total"] = sum(out["packages"].values())
dst = ROOT / "data/raw/npm-downloads/qix-week-before.json"
dst.parent.mkdir(parents=True, exist_ok=True)
dst.write_text(json.dumps(out, indent=1))
(ROOT / "frontend/src/lib/facts.ts").write_text(
    "// Generated by scripts/fetch_npm_downloads.py from data/raw/npm-downloads/qix-week-before.json. Do not edit.\n"
    f"export const QIX_WEEK_DOWNLOADS = {out['total']};\n"
    f"export const QIX_WEEK_PERIOD = \"{PERIOD}\";\n"
    f"export const QIX_PACKAGES = {len(pkgs)};\n"
    "export const QIX_DOWNLOADS_SOURCE = \"npm downloads API (api.npmjs.org), 19 packages, Sept 1 to 7, 2025\";\n")
print(out["total"])
